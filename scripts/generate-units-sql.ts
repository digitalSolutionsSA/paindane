// Prints SQL that loads src/booking/units.ts into the `units` table.
// Usage: npm run units:sql > supabase/migrations/<next number>_units.sql
//
// New units get their starting rate and "bookable online" flag; for existing units only the name,
// category, sleepers, description and order are updated, so rates set in the portal are kept.
import { UNITS } from '../src/booking/units.ts';

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);

const rows = UNITS.map((u, i) =>
  `  (${q(u.id)}, ${q(u.resort)}, ${q(u.category)}, ${q(u.name)}, ${u.sleeps ?? 'null'}, ${q(u.description)}, ${u.rate * 100}, ${u.active !== false}, ${(i + 1) * 10})`,
);

console.log(`-- Generated by scripts/generate-units-sql.ts from src/booking/units.ts
insert into units (id, resort, category, name, sleeps, description, rate_cents, is_active, sort)
values
${rows.join(',\n')}
on conflict (id) do update set
  resort = excluded.resort,
  category = excluded.category,
  name = excluded.name,
  sleeps = excluded.sleeps,
  description = excluded.description,
  sort = excluded.sort,
  updated_at = now();`);
